def _shelf_price(x: float) -> float:
    """Round to a price a shelf tag would show: 3.07 → 2.99, 3.40 → 3.49."""
    whole = int(x)
    for cents in (0.29, 0.49, 0.79, 0.99):
        if x <= whole + cents + 0.1:
            return round(whole + cents, 2)
    return round(whole + 1.29, 2)


def offers() -> list[dict]:
    """Every seeded offer as a row for the offers table."""
    aisle = {row[0]: row[2] for row in INGREDIENTS}
    name = {row[0]: row[1] for row in INGREDIENTS}
    rows: list[dict] = []
    for iid, (product, qty, unit, price) in TRADER_JOES.items():
        rows.append({"ingredient_id": iid, "store": "tj", "product": product,
                     "pkg_qty": qty, "pkg_unit": unit, "price": price, "source": "seed"})
        for store, factors in SCALE.items():
            # The other stores get the generic name, not a Trader Joe's label.
            rows.append({"ingredient_id": iid, "store": store,
                         "product": name[iid] + _size_suffix(product),
                         "pkg_qty": qty, "pkg_unit": unit,
                         "price": _shelf_price(price * factors[aisle[iid]]),
                         "source": "scaled"})
    for iid, by_store in ELSEWHERE.items():
        for store, (product, qty, unit, price) in by_store.items():
            rows.append({"ingredient_id": iid, "store": store, "product": product,
                         "pkg_qty": qty, "pkg_unit": unit, "price": price, "source": "seed"})
    return rows


def _size_suffix(product: str) -> str:
    return "," + product.split(",", 1)[1] if "," in product else ""
